# 运行指定问题
run_question() {
    local idx=$1
    local question="${QUESTIONS[$idx]}"
    local name="${NAMES[$idx]}"
    local output_file="$OUTPUT_DIR/${name}.txt"

    echo "=== 运行 Q$((idx+1)): $name ==="
    echo "问题: ${question:0:60}..."

    cd /opt/git/hermes-agent
    timeout $TIMEOUT_SECS $HERMES chat -q "$question" > "$output_file" 2>&1

    if [ $? -eq 0 ]; then
        echo "  ✅ 完成 ($(wc -c < "$output_file") 字节)"
    else
        echo "  ❌ 超时或失败"
    fi
    sleep $INTERVAL
}

# 主逻辑
if [ -n "$1" ]; then
    # 运行指定问题
    run_question $(( $1 - 1 ))
else
    # 运行所有问题
    echo "=== 开始运行 ${#QUESTIONS[@]} 个测试问题(经 hermes-safe wrapper) ==="
    for i in "${!QUESTIONS[@]}"; do
        run_question $i
        echo ""
    done
    echo "=== 全部完成 ==="
fi
