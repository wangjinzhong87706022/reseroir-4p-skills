# 运行单个测试
run_test() {
    local qnum=$1
    local question="${QUESTIONS[$qnum]}"

    if [ -z "$question" ]; then
        echo "Q$qnum: 问题为空，跳过"
        return
    fi

    echo "=========================================="
    echo "Q$qnum: $question"
    echo "=========================================="

    # 运行hermes
    local response
    response=$(timeout 300 hermes -z "$question" -s powerelf/early-warning-v3 2>"$LOG_DIR/Q${qnum}.log")
    local exit_code=$?

    # 保存响应
    echo "$response" > "$RESULTS_DIR/Q${qnum}.txt"

    if [ $exit_code -eq 124 ]; then
        echo "Q$qnum: 超时"
        echo "Q$qnum,timeout,,," >> "$RESULTS_DIR/summary.csv"
    elif [ $exit_code -ne 0 ]; then
        echo "Q$qnum: 错误 (exit code: $exit_code)"
        echo "Q$qnum,error,,," >> "$RESULTS_DIR/summary.csv"
    else
        echo "Q$qnum: 完成"
        echo "Q$qnum,done,,," >> "$RESULTS_DIR/summary.csv"
    fi

    echo ""
}

# 初始化汇总文件
echo "question_id,status,e1,e2,e3,e4,e5,e6,total,notes" > "$RESULTS_DIR/summary.csv"

# 运行测试
echo "开始基线测试..."
echo "题号范围: Q$START - Q$END"
echo ""

for i in $(seq $START $END); do
    run_test $i
done

